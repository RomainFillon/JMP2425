#!/usr/bin/env Rscript
# 01c_reemit_tab_oh_bounds.R -- reconstruit tab_oh_bounds.tex depuis ses CSV
# archives, SANS reestimer.
#
# POURQUOI. La note du tableau donnait a ses DEUX tirets une raison qui ne vaut
# que pour l'un : « that scheme's identifying climate variation has collapsed ».
# C'est vrai d'importer x year (F joint < 1). C'est FAUX d'exporter x year, dont
# le texte de B.2 dit explicitement que 50 % de la variation identifiante
# survit -- ce qu'il perd est la PRECISION. La note expliquait par
# l'effondrement un tiret que le texte explique par l'imprecision.
#
# CE QUI REND LA REEMISSION POSSIBLE : comme les tables d'absorption, celle-ci
# est une FONCTION de deux CSV archives -- `oh_scheme_effects.csv` (la moitie
# haute) et `oh_hotslope_schemes.csv` (la ligne de pente et les verdicts
# `identified`). 01c les ecrit AVANT de composer la table, exactement pour
# cela : « sans lui elle n'existait que dans le .tex rendu ».
#
# ⛔ LE TEXTE DE LA TABLE VIT DONC A DEUX ENDROITS. On ferme la surface de
#    divergence par une PREUVE, pas par une promesse : le script verifie que sa
#    reconstruction ne differe du disque QUE sur les lignes de la note, et
#    ARRETE si elle differe ailleurs. Verification AVANT toute ecriture.

suppressWarnings(suppressMessages(library(data.table)))

.self <- tryCatch(normalizePath(sub('^--file=', '', grep('^--file=',
         commandArgs(trailingOnly = FALSE), value = TRUE)[1])), error = function(e) NA)
ROOT <- if (!is.na(.self)) dirname(dirname(.self)) else getwd()
source(file.path(ROOT, '01_estimation', '00_parameters.R'), chdir = TRUE)

cat('=== reemission de tab_oh_bounds.tex (sans reestimation) ===\n')

p_eff <- file.path(DIR_OUT, 'oh_scheme_effects.csv')
p_sch <- file.path(DIR_OUT, 'oh_hotslope_schemes.csv')
for (p in c(p_eff, p_sch))
  if (!file.exists(p)) stop('[STOP] ', p, ' absent. Aucun repli.')
eff_dt <- fread(p_eff)
sch_dt <- fread(p_sch)

tex_header <- function(prod, src)
  c(sprintf('%%%% GENERATED by %s -- DO NOT EDIT BY HAND.', prod),
    sprintf('%%%% Source: %s', src))
tex_note <- function(nc, lignes)
  c(sprintf('\\multicolumn{%d}{p{\\dimexpr\\linewidth-2\\tabcolsep\\relax}}{\\footnotesize', nc),
    lignes, '}')

## ---- copie CONFORME de 01c_robustness.R l.686-762, note exceptee -----------
COLS <- list(list(task = "A", scheme = "baseline", head = "Baseline"),
             list(task = "A", scheme = "exporter", head = "Exporter$\\times$year"),
             list(task = "A", scheme = "importer", head = "Importer$\\times$year"),
             list(task = "C", scheme = "noy",      head = "Without income"))
keep <- vapply(COLS, function(c0)
  nrow(eff_dt[task == c0$task & scheme == c0$scheme]) > 0L, logical(1))
if (!any(keep)) stop('[STOP] aucune colonne disponible.')
COLS <- COLS[keep]
temps <- sort(unique(eff_dt$temp_C))
nc <- length(COLS) + 1L

cell_eff <- function(c0, t) {
  v <- eff_dt[task == c0$task & scheme == c0$scheme & temp_C == t, rel_effect_pct]
  if (!length(v)) "---" else sprintf("%.2f", v[1])
}
## THE POINT IS THE POINT ESTIMATE (lot 34, 25/09/2026): (y30 - y20)/10 from the
## rows of this same table -- the object the text cites as \EMPohSlopeLo/Hi. It
## was slope_q50, the Monte-Carlo median. Same code as 01c_robustness.R.
slope_point <- function(c0) {
  y <- function(t) eff_dt[task == c0$task & scheme == c0$scheme & temp_C == t, rel_effect_pct]
  a <- y(30); b <- y(20)
  if (length(a) != 1L || length(b) != 1L)
    stop("[STOP] pente ponctuelle : effets a 20 et 30 C introuvables pour ",
         c0$task, "/", c0$scheme)
  (a - b) / 10
}
cell_slope <- function(c0) {
  r <- sch_dt[task == c0$task & scheme == c0$scheme]
  if (!nrow(r)) return("---")
  pt <- slope_point(c0)
  if (!isTRUE(as.logical(r$identified[1])))
    return(sprintf("%.2f \\; [---]", pt))
  sprintf("%.2f \\; [%.2f, %.2f]", pt, r$slope_q05[1], r$slope_q95[1])
}
## The TWO FORMER slope formats, used ONLY by the guard below. The disk row must
## be rebuilt byte for byte from the same CSVs under one of them, which proves
## that no band value moved: only the format, and the object of the point
## (MC median -> point estimate), change.
##   fmt 0 (before 25/09, lot 32): median %.0f, bounds %.0f
##   fmt 1 (lot 32 -> lot 34)    : median %.0f, bounds %.2f
cell_slope_former <- function(c0, fb) {
  r <- sch_dt[task == c0$task & scheme == c0$scheme]
  if (!nrow(r)) return("---")
  if (!isTRUE(as.logical(r$identified[1])))
    return(sprintf("%.0f \\; [---]", r$slope_q50[1]))
  sprintf(paste0("%.0f \\; [", fb, ", ", fb, "]"), r$slope_q50[1], r$slope_q05[1], r$slope_q95[1])
}

## LA NOTE, CORRIGEE LE 22/09/2026 -- la seule chose qui change.
## LOT 74 (01/10/2026, P2) : la note disait « under exporter x year effects the
## band includes zero ». Depuis la reprise, c'est la SEULE bande qui exclut zero
## (la table l'imprime : [-2.06, -0.10]). La note ne nomme plus le schema : elle
## dit la regle, et la bande imprimee marque le schema. Meme texte que 01c.
NOTE <- c(
  "\\textit{Note.} Exporter$\\times$year fixed effects absorb the exporter",
  "capability term in full, so the response is identified off importer",
  "climate only; the importer scheme is the mirror. The last column drops",
  "bilateral income, which is a bad control: it is itself a consequence of",
  "climate. The slope is the point estimate, $(y_{30}-y_{20})/10$ from the",
  "rows above, with the $[Q_{05},Q_{95}]$ Monte-Carlo band in brackets where",
  "the band excludes zero; where it contains zero (---) no band is reported,",
  "since it would not bound the slope. Under importer$\\times$year effects the",
  "identifying climate variation has, in addition, collapsed.")

L <- c(tex_header("01c_robustness.R (R4ter)",
                  "oh_scheme_effects.csv + oh_hotslope_schemes.csv"),
  "\\begin{table}[H]\\centering\\small",
  paste0("\\caption{Bounds on the productivity dose-response under asymmetric ",
         "fixed effects and without the income control. Relative effect (\\%, ",
         "normalised to each scheme's own maximum) at reference temperatures, ",
         "and the hot-side slope with its Monte-Carlo band.}"),
  "\\label{tab:oh_bounds}",
  sprintf("\\begin{tabular}{l%s}", paste(rep("c", length(COLS)), collapse = "")),
  "\\toprule",
  paste0(" & ", paste(vapply(COLS, function(c0) c0$head, character(1)),
                      collapse = " & "), " \\\\"),
  "\\midrule",
  sprintf("\\multicolumn{%d}{l}{\\textit{Relative effect on productivity (\\%%, max $=0$)}}\\\\", nc))
for (t in temps)
  L <- c(L, sprintf("\\quad %g$^\\circ$C & %s \\\\", t,
                    paste(vapply(COLS, cell_eff, character(1), t = t), collapse = " & ")))
L <- c(L, "\\midrule",
  sprintf("Hot-side slope 20$\\to$30$^\\circ$C (\\%%/$^\\circ$C) & %s \\\\",
          paste(vapply(COLS, cell_slope, character(1)), collapse = " & ")),
  "\\bottomrule", tex_note(nc, NOTE), "\\end{tabular}", "\\end{table}")

## ---- PREUVE DE NON-DIVERGENCE, AVANT ECRITURE ------------------------------
cible <- file.path(DIR_OUT, 'tab_oh_bounds.tex')
if (file.exists(cible)) {
  d <- readLines(cible, warn = FALSE)
  ## On compare hors note : tout ce qui n'est pas dans le bloc de note doit
  ## etre IDENTIQUE AU BIT. La note est le seul changement autorise.
  bloc <- function(x) {
    i <- grep('textit\\{Note', x)[1]
    j <- grep('^\\}$', x)
    j <- j[j > i][1]
    list(avant = x[seq_len(i - 1L)], apres = x[(j + 1L):length(x)])
  }
  bd <- bloc(d); bl <- bloc(L)
  ## WIDENED 25/09/2026, AS NARROWLY AS POSSIBLE: besides the note, the ONLY
  ## line allowed to differ is the hot-side slope row, and only if the disk
  ## row equals, byte for byte, the row rebuilt from the same CSV under the
  ## LEGACY format (bounds at zero decimals). Any other difference stops.
  is_slope <- function(x) grepl('^Hot-side slope', x)
  former_row <- function(fb)
    sprintf("Hot-side slope 20$\\to$30$^\\circ$C (\\%%/$^\\circ$C) & %s \\\\",
            paste(vapply(COLS, cell_slope_former, character(1), fb = fb), collapse = ' & '))
  legacy_rows <- c(former_row("%.0f"), former_row("%.2f"))
  sd <- which(is_slope(bd$avant)); sl <- which(is_slope(bl$avant))
  if (length(sd) != 1L || length(sl) != 1L || sd != sl)
    stop('[STOP] ligne de pente introuvable ou deplacee. Rien n a ete ecrit.')
  ## The disk row may be in the legacy format (before the first re-emission)
  ## or in the current one (after it): both are rebuilt from the same CSV, so
  ## either match proves the values. Anything else is a value that moved.
  if (!(bd$avant[sd] %in% legacy_rows || identical(bd$avant[sd], bl$avant[sl])))
    stop('[STOP] la ligne de pente du disque ne se reconstruit depuis le CSV ',
         'ni au format ancien ni au format courant : une VALEUR a bouge. ',
         'Rien n a ete ecrit.')
  bd$avant[sd] <- bl$avant[sl]      # seule substitution autorisee
  if (!identical(bd$avant, bl$avant) || !identical(bd$apres, bl$apres))
    stop('[STOP] la reconstruction differe du disque AILLEURS que dans la note. ',
         'Les deux copies du texte ont diverge : ce script et 01c l.686-762 ',
         'doivent etre realignes AVANT toute reemission. Rien n a ete ecrit.')
  cat('  [preuve] tout ce qui n est pas la note est IDENTIQUE AU BIT',
      ' hors note et hors format des bornes de la ligne de pente',
      ' (valeurs prouvees identiques par la ligne au format ancien)\n', sep = '')
} else {
  cat('  [!] cible absente : preuve de non-divergence NON CONCLUANTE\n')
}

writeLines(L, cible)
cat('  [write] tab_oh_bounds.tex\n=== termine ===\n')
