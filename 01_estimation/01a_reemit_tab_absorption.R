#!/usr/bin/env Rscript
# 01a_reemit_tab_absorption.R -- reconstruit les DEUX tables d'absorption
# depuis leurs CSV archives, SANS reestimer.
#
# POURQUOI IL EXISTE. La note de `tab_ctrl_absorption.tex` portait
# `$\theta^k\cdot\log(y_s/y_r)$` dans sa liste de controles -- deux erreurs dans
# le meme symbole (l'indice k, et un coefficient CONTRAINT la ou `GDP_diff` est
# un regresseur LIBRE de TRADE_STAGE3_CONTROLS). Le producteur, 01a, a ete
# corrige le 22/09/2026 ; mais 01a est une estimation PPML, et refaire une
# LEGENDE ne peut pas couter un PPML.
#
# CE QUI REND CELA POSSIBLE, ET C'EST DEJA LA REGLE DE CE PAQUET. 01a archive
# ses deux tableaux de R2 en CSV (l.553 et l.564) avant d'en composer les
# tables. Les CSV portent TOUTES les colonnes que les tables consomment, y
# compris les `*_raw` non arrondies des legendes. La table est donc une
# FONCTION du CSV, et rien d'autre.
#   -> meme geste que l'archivage de `eff` le 11/09/2026 : « sans CSV, la seule
#      trace en etait le .tex rendu, et reconstruire obligeait soit a recopier
#      des valeurs d'un .tex (interdit), soit a relancer une estimation ».
#
# LA GARDE DE NON-DIVERGENCE, ET C'EST LE POINT DELICAT. Le texte des tables
# vit desormais a DEUX endroits : ici et dans 01a. Une duplication est une
# surface de divergence. On la ferme par un CONTROLE plutot que par un
# refactor non testable : ce script verifie que sa reconstruction de
# `tab_fe_absorption.tex` -- la table que PERSONNE n'a modifiee -- est
# IDENTIQUE AU BIT a celle qui est sur disque. Si les deux copies du texte
# divergent un jour, ce controle le dit ici, bruyamment, avant d'ecrire quoi
# que ce soit.
#   ⛔ Et il le verifie AVANT d'ecrire. Un refus doit laisser l'artefact
#      precedent intact (regle du 11/09 : `open(p,'w')` tronque avant de
#      calculer).

suppressWarnings(suppressMessages({
  library(data.table)
}))

.self <- tryCatch(normalizePath(sub('^--file=', '', grep('^--file=',
         commandArgs(trailingOnly = FALSE), value = TRUE)[1])), error = function(e) NA)
ROOT <- if (!is.na(.self)) dirname(dirname(.self)) else getwd()
source(file.path(ROOT, '01_estimation', '00_parameters.R'), chdir = TRUE)

cat('=== reemission des tables d absorption (sans reestimation) ===\n')

p1 <- file.path(DIR_OUT, 'fe_absorption.csv')
p2 <- file.path(DIR_OUT, 'ctrl_absorption.csv')
for (p in c(p1, p2))
  if (!file.exists(p))
    stop('[STOP] ', p, ' absent : la table ne peut pas etre reconstruite ',
         'sans rejouer 01a. Aucun repli.')

arg1 <- fread(p1)
arg2 <- fread(p2)

## ---- le texte des deux tables, copie CONFORME de 01a l.610-665 -------------
tab_fe <- c(
  "%% GENERATED by 01a_productivity_drf.R -- DO NOT EDIT BY HAND.",
  "\\begin{table}[H]", "\\centering\\small",
  "\\caption{Variance absorption by fixed effects}", "\\label{tab:fe_absorption}",
  "\\begin{tabular}{lccc}", "\\hline\\hline",
  "Climate term & Pair$\\times$prod FE & Prod$\\times$year FE & Both FE \\\\", "\\hline",
  sprintf("$\\Delta_%d$ & %.4f & %.6f & %.4f \\\\",
          arg1$term, arg1$r2_pair, arg1$r2_pyr, arg1$r2_both),
  "\\hline\\hline",
  "\\multicolumn{4}{p{\\dimexpr\\linewidth-2\\tabcolsep\\relax}}{\\footnotesize",
  "$R^2$ from projecting the bilateral climate differential",
  "$\\Delta_k = g_k(T(s)) - g_k(T(r))$ on fixed effects alone (OLS).",
  "Origin$\\times$destination$\\times$product fixed effects absorb",
  sprintf("at least %.1f\\%% of the variance in bilateral climate differentials",
          100 * min(arg1$r2_pair_raw)),
  sprintf("(%.1f\\%%--%.1f\\%% across the three terms), leaving insufficient",
          100 * min(arg1$r2_pair_raw), 100 * max(arg1$r2_pair_raw)),
  "residual variation for PPML identification.",
  sprintf("Product$\\times$year fixed effects absorb at most %.2f\\%%,",
          100 * max(arg1$r2_pyr_raw)),
  "preserving the between-pair variation that identifies $g(\\cdot)$.}",
  "\\end{tabular}", "\\end{table}")

tab_ctrl <- c(
  "%% GENERATED by 01a_productivity_drf.R -- DO NOT EDIT BY HAND.",
  "\\begin{table}[H]", "\\centering\\small",
  "\\caption{Absorption of between-pair confounders by gravity controls}",
  "\\label{tab:ctrl_absorption}",
  "\\begin{tabular}{lccc}", "\\hline\\hline",
  "Climate term & $R^2$ (FE only) & $R^2$ (FE + controls) & Absorbed \\\\", "\\hline",
  sprintf("$\\Delta_%d$ & %.6f & %.4f & %.4f \\\\",
          arg2$term, arg2$r2_fe_only, arg2$r2_fe_ctrl, arg2$r2_absorbed),
  "\\hline\\hline",
  "\\multicolumn{4}{p{\\dimexpr\\linewidth-2\\tabcolsep\\relax}}{\\footnotesize",
  "OLS projection of $\\Delta_k$ on gravity controls conditional on",
  "product$\\times$year fixed effects. Gravity controls (log bilateral distance,",
  ## 🚨 23/09/2026 (lot 25) : `$\theta^k$` RETABLI. Le retrait du 22/09
  ## reposait sur une confusion : « libre » qualifiait le COEFFICIENT de
  ## `GDP_diff`, pas sa CONSTRUCTION. Le regresseur est theta_k * log(y_o/y_d)
  ## (01a l.411), theta_k variant par division (17 valeurs sur 20 secteurs) ;
  ## un coefficient scalaire n'en absorbe que R2 = 0,38 (RECAP §3.197). La
  ## legende nomme donc le regresseur TEL QU'IL EST CONSTRUIT ; son
  ## coefficient reste libre, ce que dit l'eq. (5) (zeta_y).
  "common language, colonial link, WTO FTA, $\\theta^k\\cdot\\log(y_s/y_r)$)",
  sprintf("absorb %.1f--%.1f\\%% of the between-pair climate variation,",
          100 * min(arg2$r2_absorbed_raw), 100 * max(arg2$r2_absorbed_raw)),
  "partially controlling for the main observable confounders.}",
  "\\end{tabular}", "\\end{table}")

## ---- CONTROLE DE NON-DIVERGENCE, AVANT TOUTE ECRITURE ---------------------
## tab_fe_absorption n'a PAS ete modifiee : sa reconstruction doit donc etre
## identique au bit a ce qui est sur disque. Si elle ne l'est pas, les deux
## copies du texte ont divergé et on ne publie rien.
ref_fe <- file.path(DIR_OUT, 'tab_fe_absorption.tex')
if (file.exists(ref_fe)) {
  disque <- readLines(ref_fe, warn = FALSE)
  if (!identical(disque, tab_fe)) {
    d <- which(seq_len(max(length(disque), length(tab_fe))) %in%
               which(disque[seq_len(min(length(disque), length(tab_fe)))] !=
                     tab_fe[seq_len(min(length(disque), length(tab_fe)))]))
    stop('[STOP] la reconstruction de tab_fe_absorption.tex DIFFERE du disque ',
         '(', length(disque), ' vs ', length(tab_fe), ' lignes ; premieres ',
         'divergences aux lignes ', paste(utils::head(d, 5), collapse = ', '),
         '). Les deux copies du texte ont diverge : ce script et 01a l.610-631 ',
         'doivent etre realignes AVANT toute reemission. Rien n a ete ecrit.')
  }
  cat('  [garde] tab_fe_absorption.tex reconstruite IDENTIQUE AU BIT',
      ' -> les deux copies du texte sont alignees\n', sep = '')
} else {
  cat('  [!] tab_fe_absorption.tex absente : garde de non-divergence NON',
      ' CONCLUANTE (on ecrit quand meme tab_ctrl, mais sans ce temoin)\n', sep = '')
}

writeLines(tab_fe,   ref_fe)
writeLines(tab_ctrl, file.path(DIR_OUT, 'tab_ctrl_absorption.tex'))
cat('  [write] tab_fe_absorption.tex + tab_ctrl_absorption.tex\n')
cat('=== termine ===\n')
